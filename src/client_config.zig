const std = @import("std");
const Io = std.Io;

pub const ResolvConf = struct {
    nameservers: [MAX_NS]Io.net.IpAddress = undefined,
    num_servers: u8 = 0,

    pub fn parse(reader: *Io.Reader) !ResolvConf {
        var ret = ResolvConf{};
        while ((try reader.peekByte()) == '#') {
            _ = try reader.discardDelimiterInclusive('\n');
        }
        while (true) {
            if (ret.num_servers >= MAX_NS) break;
            const valid = expectBytes(reader, "nameserver") catch |err| switch (err) {
                error.EndOfStream => break,
                else => return err,
            };

            if (valid) {
                reader.toss(11);
                const addr_bytes = try reader.takeDelimiterExclusive('\n');
                ret.nameservers[ret.num_servers] = try Io.net.IpAddress.parse(addr_bytes, 53);
                ret.num_servers += 1;
            } else {
                _ = reader.discardDelimiterInclusive('\n') catch |err| switch (err) {
                    error.EndOfStream => break,
                    else => return err,
                };
            }
        }
        return ret;
    }

    pub fn default(io: Io) !ResolvConf {
        var fd = try Io.Dir.openFileAbsolute(io, "/etc/resolv.conf", .{ .mode = .read_only });
        defer fd.close(io);
        var buffer: [512]u8 = undefined;
        var reader = fd.reader(io, &buffer);
        return ResolvConf.parse(&reader.interface);
    }
};

const MAX_NS = 10;

fn expectBytes(r: *std.Io.Reader, expected: []const u8) !bool {
    const got = try r.peek(expected.len);
    return std.mem.eql(u8, got, expected);
}

test "resolv.conf" {
    // const bytes =
    //     \\# This file is automatically generated.
    //     \\#
    //     \\something else
    //     \\nameserver 2001:db8::7
    //     \\nameserver 10.31.33.7
    //     \\nameserver 9.9.9.11
    //     \\nameserver 149.112.112.11
    //     \\nameserver 2620:fe::11
    //     \\nameserver 2620:fe::fe:11
    // ;
    const io = std.testing.io;

    const resolv = try ResolvConf.default(io);

    for (0..resolv.num_servers) |i| {
        std.debug.print("{f}\n", .{resolv.nameservers[i]});
    }
}
